// Copies the overworld density-function, noise and noise-settings JSON from vanilla-data into
// crates/rine-worldgen/assets/ and writes src/density/assets.rs with one include_str! per file.
// Usage: node tools/noise-golden/copy_density_assets.js   (run from anywhere; paths are absolute)
const fs = require('fs');
const path = require('path');

const REPO = path.resolve(__dirname, '..', '..');
const SRC = path.join(REPO, 'vanilla-data', 'generated', 'data', 'minecraft', 'worldgen');
const CRATE = path.join(REPO, 'crates', 'rine-worldgen');
const ASSETS = path.join(CRATE, 'assets');

function walk(dir, out = []) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
        const p = path.join(dir, ent.name);
        if (ent.isDirectory()) walk(p, out);
        else if (ent.name.endsWith('.json')) out.push(p);
    }
    return out;
}

const files = [];
// Top-level density functions (shift_x, shift_z, y, zero) and the whole overworld folder.
for (const f of fs.readdirSync(path.join(SRC, 'density_function'))) {
    const p = path.join(SRC, 'density_function', f);
    if (f.endsWith('.json')) files.push(p);
}
files.push(...walk(path.join(SRC, 'density_function', 'overworld')));
files.push(...walk(path.join(SRC, 'noise')));
files.push(path.join(SRC, 'noise_settings', 'overworld.json'));
// Surface rules (overworld material rule tree, bedrock floor/roof) and the named conditions they reference.
files.push(path.join(SRC, 'material_rule', 'overworld.json'), path.join(SRC, 'material_rule', 'bedrock_floor.json'), path.join(SRC, 'material_rule', 'bedrock_roof.json'));
files.push(...walk(path.join(SRC, 'material_rule', 'overworld')));
files.push(...walk(path.join(SRC, 'material_condition')));

// Only the generated subtrees are replaced; hand-maintained files under assets/ (worldgen/) stay.
for (const sub of ['density_function', 'noise', 'noise_settings', 'material_rule', 'material_condition']) {
    fs.rmSync(path.join(ASSETS, sub), { recursive: true, force: true });
}
const entries = [];
for (const src of files.sort()) {
    const rel = path.relative(SRC, src).split(path.sep).join('/');
    const dst = path.join(ASSETS, rel);
    fs.mkdirSync(path.dirname(dst), { recursive: true });
    fs.copyFileSync(src, dst);
    entries.push(rel);
}

let rs = '// @generated by tools/noise-golden/copy_density_assets.js. Do not edit.\n';
rs += '//! Bundled vanilla 26.3 worldgen JSON (density functions, noises, overworld settings).\n\n';
rs += 'pub const FILES: &[(&str, &str)] = &[\n';
for (const rel of entries) {
    rs += `    ("${rel}", include_str!("../../assets/${rel}")),\n`;
}
rs += '];\n';
fs.mkdirSync(path.join(CRATE, 'src', 'density'), { recursive: true });
fs.writeFileSync(path.join(CRATE, 'src', 'density', 'assets.rs'), rs);
console.log(`bundled ${entries.length} files`);
